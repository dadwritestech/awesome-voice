"""Copy the checker into docs/ for the slop score page.

    python scripts/build_web.py

docs/slop.js is plugin/slop/slop.js byte for byte; docs/tells.js wraps
tells.json for the browser. tests/test_web_sync.py fails if they go stale.
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def tells_js() -> str:
    data = json.loads((ROOT / "plugin" / "slop" / "tells.json").read_text(encoding="utf-8"))
    return "// Generated by scripts/build_web.py from plugin/slop/tells.json. Do not edit.\nwindow.SLOP_TELLS = " + \
        json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"


def main():
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    shutil.copyfile(ROOT / "plugin" / "slop" / "slop.js", docs / "slop.js")
    (docs / "tells.js").write_text(tells_js(), encoding="utf-8", newline="\n")
    print("wrote docs/slop.js and docs/tells.js")


if __name__ == "__main__":
    main()
